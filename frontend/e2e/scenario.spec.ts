import { test, expect } from '@playwright/test'
test('snapshot to constrained exact-version simulated approval',async({page})=>{
 test.skip(!process.env.FIELDLINK_E2E_PASSWORD,'Requires a provisioned local supervisor password; no external messaging is used')
 await page.goto('/')
 await page.getByLabel('Username').fill('supervisor')
 await page.getByLabel('Password',{exact:true}).fill(process.env.FIELDLINK_E2E_PASSWORD!)
 await page.getByRole('button',{name:'Sign in',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Operations overview'})).toBeVisible()
 await page.getByLabel('Dataset',{exact:true}).selectOption({label:'snapshot_2026-10-08T1200'})
 await page.getByLabel('Run mode').selectOption('scenario')
 await page.getByRole('button',{name:'New run'}).click()
 await expect(page.getByRole('button',{name:/pump failure.*S2_FACILITY_B/i})).toBeVisible({timeout:20000})
 await page.getByRole('button',{name:'Compare plans',exact:true}).click()
 await expect(page.getByText(/Version 1/)).toBeVisible({timeout:20000})
 await page.getByRole('link',{name:'Conversations',exact:true}).click()
 await page.getByLabel('Operator report').fill('S2_TRUCK_1 unavailable for 60 scenario minutes')
 await page.getByRole('button',{name:'Send report'}).click()
 await expect(page.getByText(/Confirmed S2_TRUCK_1/)).toBeVisible({timeout:20000})
 await page.getByRole('link',{name:/Overview/}).click()
 await expect(page.getByText(/Version 2/)).toBeVisible()
 await page.getByRole('button',{name:'Approve simulated plan'}).click()
 await expect(page.getByText('SIMULATED DISPATCHED',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Acknowledge simulated dispatch'}).click()
 await expect(page.getByText('ACKNOWLEDGED',{exact:true})).toBeVisible()
 await page.evaluate(()=>window.scrollTo(0,0))
 await page.screenshot({path:'test-results/overview.png',fullPage:true})
 await page.setViewportSize({width:390,height:844})
 await page.evaluate(()=>window.scrollTo(0,0))
 await page.screenshot({path:'test-results/mobile.png',fullPage:true})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
})
